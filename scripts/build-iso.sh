#!/usr/bin/env bash
# Build the Sona Linux live ISO with archiso.
#
# Usage (on an Arch Linux system, from anywhere):
#   sudo scripts/build-iso.sh
#
# The ISO is written to out/ at the top of the repository.
#
# The ISO holds everything an installed Sona system has (the package lists
# come from the SONA PACKAGES block in Install), so the installer can copy
# the live system to the disk with no internet.
#
# Private builds only: SONA_BUNDLE_XP_SOUNDS=/path/to/windows-xp copies those
# .wav files into the ISO, so the XP theme needs no download. The sounds
# belong to Microsoft, so never set this for an ISO you share or publish.
#   sudo SONA_BUNDLE_XP_SOUNDS=$HOME/.local/share/sounds/windows-xp scripts/build-iso.sh

set -euo pipefail

repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_profile="$repo_dir/sona-live"
profile_dir="$repo_dir/work-profile"
work_dir="$repo_dir/work"
out_dir="$repo_dir/out"

if [[ $EUID -ne 0 ]]; then
    echo "Error: run this script as root, for example: sudo $0" >&2
    exit 1
fi

if ! command -v mkarchiso >/dev/null 2>&1; then
    echo "Error: mkarchiso is missing. Install it with: pacman -S archiso" >&2
    exit 1
fi

# --- The profile for this build: a copy of sona-live plus generated files,
# so nothing generated is ever written into the git tree.
rm -rf "$profile_dir"
cp -a "$source_profile" "$profile_dir"
air="$profile_dir/airootfs"

# Every package an installed system gets, from Install's SONA PACKAGES block.
pkg_block="$(sed -n '/^# BEGIN SONA PACKAGES$/,/^# END SONA PACKAGES$/p' "$repo_dir/Install")"
[[ -n "$pkg_block" ]] || { echo "Error: no SONA PACKAGES block in Install." >&2; exit 1; }
eval "$pkg_block"
{
    echo
    echo "# --- Generated by scripts/build-iso.sh from Install (SONA PACKAGES) ---"
    printf '%s\n' "${SONA_BASE_PKGS[@]}" "${SONA_UCODE_PKGS[@]}" "${SONA_X_PKGS[@]}" \
        "${SONA_DESKTOP_PKGS[@]}" "${SONA_APP_PKGS[@]}" "${SONA_XP_PKGS[@]}" \
        "${SONA_KOKORO_PKGS[@]}" "${SONA_STORMUX_PKGS[@]}" "${SONA_NVIDIA_PKGS[@]}"
} >> "$profile_dir/packages.x86_64"
# Each package once.
awk '/^#/ || NF == 0 || !seen[$1]++' "$profile_dir/packages.x86_64" > "$profile_dir/packages.tmp"
mv "$profile_dir/packages.tmp" "$profile_dir/packages.x86_64"

# The list of files the live system adds on top of its packages. When the
# installer copies the live system to a disk, it deletes these and writes
# the installed system's own versions. Files every system needs (users,
# host name, time zone, locale) are kept and rewritten by the installer.
mkdir -p "$air/usr/share/sona"
{
    (cd "$source_profile/airootfs" && find . \( -type f -o -type l \) -printf '%P\n')
    echo "usr/local/bin/sona-install"
} | grep -v -x -E 'etc/(passwd|group|shadow|gshadow|hostname|locale\.conf|localtime|environment|resolv\.conf|pacman\.conf)' \
    | sort -u > "$air/usr/share/sona/live-files.txt"

# The installer, run on the live ISO as sona-install.
install -Dm755 "$repo_dir/Install" "$air/usr/local/bin/sona-install"

# Extras the installer copies to installed systems: the Windows XP theme
# kit, Orca Bridge, the Kokoro setup, and Sona's own PKGBUILDs (OpenEVV).
cp -r "$repo_dir/xp-theme" "$air/usr/share/sona/xp-theme"
install -Dm755 "$repo_dir/xp-theme/sona-xp-firstrun" "$air/usr/local/bin/sona-xp-firstrun"
cp -r "$repo_dir/orca-bridge" "$air/usr/share/sona/orca-bridge"
install -Dm755 "$repo_dir/orca-bridge/sona-orca-extensions" "$air/usr/local/bin/sona-orca-extensions"
cp -r "$repo_dir/kokoro" "$air/usr/share/sona/kokoro"
install -Dm755 "$repo_dir/kokoro/sona-kokoro-setup" "$air/usr/local/bin/sona-kokoro-setup"
cp -r "$repo_dir/packages" "$air/usr/share/sona/packages"

# The Kokoro voice model and Python packages (Apache-2.0, about 450 MB),
# so Kokoro works with no internet. Downloaded once and kept in out/cache.
# The Python packages are for this computer's Python version, which is the
# same one the ISO gets (both are current Arch).
command -v pip >/dev/null 2>&1 || python3 -m pip --version >/dev/null 2>&1 ||
    { echo "Error: pip is missing. Install it with: pacman -S python-pip" >&2; exit 1; }
kokoro_cache="$out_dir/cache/kokoro-py$(python3 -c 'import sys; print(f"{sys.version_info.major}{sys.version_info.minor}")')"
mkdir -p "$kokoro_cache"
"$repo_dir/kokoro/sona-kokoro-setup" --fetch-only "$kokoro_cache"
mkdir -p "$air/opt/kokoro-speechd"
cp -r "$kokoro_cache/models" "$kokoro_cache/site-packages" "$air/opt/kokoro-speechd/"

if [[ -n "${SONA_BUNDLE_XP_SOUNDS:-}" ]]; then
    wavs=("$SONA_BUNDLE_XP_SOUNDS"/*.wav)
    if [[ ! -f "${wavs[0]}" ]]; then
        echo "Error: no .wav files in SONA_BUNDLE_XP_SOUNDS=$SONA_BUNDLE_XP_SOUNDS" >&2
        exit 1
    fi
    mkdir -p "$air/usr/share/sona/xp-sounds"
    cp "${wavs[@]}" "$air/usr/share/sona/xp-sounds/"
    echo "PRIVATE BUILD: ${#wavs[@]} Windows XP sounds included. Do not share this ISO."
fi

# --- Signing keys for the SonicDE and XLibre repositories
# (sona-live/pacman.conf). mkarchiso uses this computer's pacman keyring, so
# trust them here, but only with exactly these fingerprints. The keys are
# also put on the ISO, so an offline install can trust the same repositories.
# With "bundle-only", the key is only put on the ISO (the repository is not
# used to build it, so this computer's keyring is left alone).
trust_key() {
    local name="$1" url="$2" fpr="$3" mode="${4:-}" key_tmp got_fpr
    key_tmp="$(mktemp)"
    curl -fsSL --retry 5 --retry-delay 10 -o "$key_tmp" "$url"
    got_fpr="$(gpg --show-keys --with-colons "$key_tmp" 2>/dev/null | awk -F: '$1 == "fpr" {print $10; exit}')"
    if [[ "$got_fpr" != "$fpr" ]]; then
        rm -f "$key_tmp"
        echo "Error: the downloaded $name key has fingerprint ${got_fpr:-unknown}, expected $fpr." >&2
        exit 1
    fi
    if [[ "$mode" != bundle-only ]]; then
        if ! pacman-key --list-keys "$fpr" >/dev/null 2>&1; then
            echo "Adding the $name package signing key..."
            pacman-key --add "$key_tmp"
        fi
        pacman-key --lsign-key "$fpr" >/dev/null
    fi
    install -Dm644 "$key_tmp" "$air/usr/share/sona/keys/$(basename "$url")"
    rm -f "$key_tmp"
}
trust_key SonicDE https://sonicde-arch.github.io/sonicde-archlinux.asc A85BB166B49A4C58C39125073B87898C73F11DF5
trust_key XLibre https://xlibre-arch.github.io/xlibre-archlinux.asc 0C92313001CFCA27627B9098B97F7C613F359424
# Stormux provides wine-access for the ISO.
trust_key Stormux https://git.stormux.org/storm/stormux/raw/branch/master/x86_64/stormux_repo.pub \
    52ADA49000F1FF0456F8AEEFB4CDE1CD56EF8E82

# --- Build
rm -rf "$work_dir"
mkdir -p "$out_dir"

echo "Building the Sona Linux ISO. This can take a while..."
mkarchiso -v -w "$work_dir" -o "$out_dir" "$profile_dir"

rm -rf "$work_dir" "$profile_dir"

# Give the ISO to the user who ran sudo. Only the ISO files: never chown -R
# out/, because a quick test or VM test may have a system mounted in there
# (with this computer's /dev, /sys and package cache bind-mounted).
if [[ -n "${SUDO_USER:-}" ]]; then
    chown "$SUDO_USER:" "$out_dir" "$out_dir"/*.iso
fi

echo
echo "Done. The ISO is in $out_dir:"
ls -1 "$out_dir"/*.iso
